import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";

/**
 * esbuild.config.mjs — 加固 #Q1【S2】：本文件原缺失，按 Obsidian 官方样例插件模板复刻；
 * 加固 #P5【S3】：以 Node 内置 node:module 的 builtinModules 替代废弃包 builtin-modules，
 * external 中的 Node 内置模块清单由 builtinModules 提供，无需第三方依赖。
 */

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	// esbuild 0.17.3 的 context() 不接受 watch 选项：开发模式改由下方 context.watch() 触发
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
